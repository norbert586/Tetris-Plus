#!/usr/bin/env bash
# Installs the pinned reverse-engineering toolchain into $TP_TOOLS (default /opt/tp-tools):
# Ghidra + ghidra_psx_ldr, REA, mkpsxiso/dumpsxiso and PCSX-Redux. Safe to re-run: each tool
# is skipped when already present. Writes $TP_TOOLS/env.sh for other scripts to source.
set -euo pipefail

TP_TOOLS="${TP_TOOLS:-/opt/tp-tools}"

GHIDRA_VERSION=12.1.4
GHIDRA_ZIP="ghidra_${GHIDRA_VERSION}_PUBLIC_20260921.zip"
GHIDRA_SHA256=ddac49f903da9d5bac833e5cc79395098b9c33cfd3279be5f31bd00387d2d4db
PSX_LDR_COMMIT=3050da64925b9aad299489468000dc62b835c09a
REA_VERSION=6.5.0
MKPSXISO_TAG=v2.30
# PCSX-Redux dev build 435 (changeset 1644434975088dacd3b4b153572935a1af75f20d) from its
# update catalog at https://distrib.app/storage/manifests/pcsx-redux/dev-linux-x64/.
REDUX_PATH=/storage/assets/a13/d15/32c/f0fda2d322c2e0a454c947787bd38fd4b3150db074d2e4ccd178057/PCSX-Redux-16444349-linux-x86_64.zip
REDUX_MD5=9a1f7001dfbb142ef43fe807e1ba3d09

GHIDRA_DIR="$TP_TOOLS/ghidra_${GHIDRA_VERSION}_PUBLIC"
REA_BIN="$TP_TOOLS/rea/node_modules/.bin/rea"
MKPSXISO_SRC="$TP_TOOLS/src/mkpsxiso"
PSX_LDR_SRC="$TP_TOOLS/src/ghidra_psx_ldr"
REDUX_DIR="$TP_TOOLS/pcsx-redux"
REDUX_BIN="$REDUX_DIR/squashfs-root/usr/bin/pcsx-redux"

log() { printf '[setup] %s\n' "$*"; }

mkdir -p "$TP_TOOLS/src"

if ! command -v 7z >/dev/null; then
  log "installing 7zip"
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq 7zip >/dev/null
fi

if [ ! -x "$GHIDRA_DIR/support/analyzeHeadless" ]; then
  log "downloading Ghidra $GHIDRA_VERSION"
  curl -sSL --fail -o "$TP_TOOLS/ghidra.zip" \
    "https://github.com/NationalSecurityAgency/ghidra/releases/download/Ghidra_${GHIDRA_VERSION}_build/$GHIDRA_ZIP"
  echo "$GHIDRA_SHA256  $TP_TOOLS/ghidra.zip" | sha256sum -c --quiet
  unzip -q "$TP_TOOLS/ghidra.zip" -d "$TP_TOOLS"
  rm "$TP_TOOLS/ghidra.zip"
fi

if [ ! -f "$GHIDRA_DIR/Ghidra/Extensions/ghidra_psx_ldr/extension.properties" ]; then
  log "building ghidra_psx_ldr at $PSX_LDR_COMMIT"
  [ -d "$PSX_LDR_SRC/.git" ] || git clone -q https://github.com/lab313ru/ghidra_psx_ldr.git "$PSX_LDR_SRC"
  git -C "$PSX_LDR_SRC" checkout -q "$PSX_LDR_COMMIT"
  git -C "$PSX_LDR_SRC" submodule update --init --depth 1 -q
  gradle_bin="$(command -v gradle || ls -d /opt/gradle-*/bin/gradle 2>/dev/null | tail -1)"
  [ -n "$gradle_bin" ] || { echo "gradle not found" >&2; exit 1; }
  (cd "$PSX_LDR_SRC" && "$gradle_bin" --no-daemon -q -PGHIDRA_INSTALL_DIR="$GHIDRA_DIR" buildExtension)
  unzip -q -o "$(ls -t "$PSX_LDR_SRC"/dist/*_ghidra_psx_ldr.zip | head -1)" -d "$GHIDRA_DIR/Ghidra/Extensions"
fi

if [ ! -x "$REA_BIN" ] || [ "$("$REA_BIN" --version 2>/dev/null)" != "$REA_VERSION" ]; then
  log "installing REA $REA_VERSION"
  npm install --no-audit --no-fund --loglevel=error --prefix "$TP_TOOLS/rea" "rea-agents@$REA_VERSION"
fi

if [ ! -x "$MKPSXISO_SRC/build/dumpsxiso" ]; then
  log "building mkpsxiso $MKPSXISO_TAG"
  [ -d "$MKPSXISO_SRC/.git" ] || git clone -q --depth 1 --branch "$MKPSXISO_TAG" --recurse-submodules \
    --shallow-submodules https://github.com/Lameguy64/mkpsxiso.git "$MKPSXISO_SRC"
  cmake -S "$MKPSXISO_SRC" -B "$MKPSXISO_SRC/build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
    -DMKPSXISO_NO_LIBFLAC=1 >/dev/null
  cmake --build "$MKPSXISO_SRC/build" -j"$(nproc)" >/dev/null
fi

if [ ! -x "$REDUX_BIN" ]; then
  log "downloading PCSX-Redux"
  mkdir -p "$REDUX_DIR"
  curl -sSL --fail -o "$REDUX_DIR/redux.zip" "https://distrib.app$REDUX_PATH"
  echo "$REDUX_MD5  $REDUX_DIR/redux.zip" | md5sum -c --quiet
  (cd "$REDUX_DIR" && unzip -q -o redux.zip && rm redux.zip &&
    ./PCSX-Redux-HEAD-x86_64.AppImage --appimage-extract >/dev/null)
fi

cat > "$TP_TOOLS/env.sh" <<EOF
# Generated by scripts/setup-toolchain.sh
export TP_TOOLS="$TP_TOOLS"
export GHIDRA_INSTALL_DIR="$GHIDRA_DIR"
export GHIDRA_HEADLESS_MAXMEM="\${GHIDRA_HEADLESS_MAXMEM:-4G}"
export TP_REA="$REA_BIN"
export TP_DUMPSXISO="$MKPSXISO_SRC/build/dumpsxiso"
export TP_REDUX="$REDUX_BIN"
EOF

log "ready: source $TP_TOOLS/env.sh"
