#!/usr/bin/env python3
"""Writes the shared state block as a mode program found it at its main, for tests that start
the port at that program instead of at power-on (web/test/flow.ts compareFlow `start`), until
every program before it is ported.

  extract_entry_state.py OUT.ts CONST_NAME KEY=RAM_DUMP [KEY=RAM_DUMP ...]

Each RAM_DUMP is main RAM at the program's main (scripts/run-movie.sh with TP_MAIN_RAM=1). The
ranges are re/tools/extract_power_state.py's, widened to what the title programs read: the CD's
track count (state+0x206E0) and the attract demo toggle (state+0x4B540).
"""
import base64
import sys

STATE = 0x8003E668
RANGES = [(0x0, 0xC0), (0x1FCF4, 0x1FDF4), (0x20550, 0x206E4), (0x4AD84, 0x4B544)]


def main():
    out_path, name = sys.argv[1], sys.argv[2]
    out = [
        '// Generated by re/tools/extract_entry_state.py from emulator RAM dumps. Do not edit.',
        "// The shared state block's ranges at a program's main, by key: offset from state",
        '// (0x8003E668) and bytes.',
        f'export const {name}: Record<string, {{ offset: number; base64: string }}[]> = {{',
    ]
    for arg in sys.argv[3:]:
        key, path = arg.split('=', 1)
        ram = open(path, 'rb').read()
        out.append(f"  '{key}': [")
        for start, end in RANGES:
            a = (STATE & 0x1FFFFF) + start
            b64 = base64.b64encode(ram[a:a + end - start]).decode()
            parts = [b64[i:i + 96] for i in range(0, len(b64), 96)]
            out.append(f'    {{ offset: 0x{start:x}, base64:')
            out.append('      ' + ' +\n      '.join(f"'{p}'" for p in parts) + ' },')
        out.append('  ],')
    out.append('};')
    open(out_path, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
