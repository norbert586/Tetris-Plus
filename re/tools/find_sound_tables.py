#!/usr/bin/env python3
"""Finds the sound tables in every mode program and writes their contents for the audio layer.

  find_sound_tables.py <files dir> web/src/audio/sound-tables.ts

Every program links the same libsnd and the same se_play/bgm_play_track, with the same tables
at its own addresses (docs/re/audio.md §11): libsnd's note-to-pitch table, the per-track table
(end offset, loop mode, priority, from track 2) and the music and effect volume tables. This
finds them by PAZLE.EXE's contents, checks every program holds the same bytes, prints each
program's addresses (web/src/audio/programs.ts) and writes the bytes once.
"""
import base64
import struct
import sys

PROGRAMS = ['SW_ON', 'TIT_DEMO', 'TITLE', 'HOW_N', 'HOW_P', 'HOW_VS', 'RANKING', 'SELECT', 'NOMAL',
            'PAZLE', 'VSPUZ', 'EDIT']
# Name, PAZLE.EXE address, size.
TABLES = [('pitchTable', 0x800EC94C, 384), ('trackTable', 0x800DC610, 51 * 12),
          ('musicVolume', 0x800DC45C, 16)]


def load(path):
    d = open(path, 'rb').read()
    addr, size = struct.unpack_from('<II', d, 0x18)
    return addr, d[0x800:0x800 + size]


def main():
    files, out = sys.argv[1], sys.argv[2]
    pa, pd = load(f'{files}/PAZLE.EXE')
    tables = {name: pd[a - pa:a - pa + n] for name, a, n in TABLES}
    for prog in PROGRAMS:
        a, d = load(f'{files}/{prog}.EXE')
        found = []
        for name, data in tables.items():
            i = d.find(data)
            if i < 0:
                sys.exit(f'{prog}: no {name}')
            found.append(f'{name}: 0x{a + i:08x}')
        print(f'{prog}: {", ".join(found)}')
    lines = [
        f'// Generated by re/tools/find_sound_tables.py (SLUS-00338). Do not edit.',
        '// The sound tables every program holds, the same bytes in each (addresses: programs.ts).',
        'export const SOUND_TABLES: Record<string, string> = {',
    ]
    for name, data in tables.items():
        b64 = base64.b64encode(data).decode()
        parts = [b64[i:i + 96] for i in range(0, len(b64), 96)]
        lines.append(f'  {name}:\n    ' + ' +\n    '.join(f"'{p}'" for p in parts) + ',')
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
