#!/usr/bin/env python3
"""Writes the part of the boot program's shared state block that PAZLE.EXE finds already set
when it starts (web/src/core/boot-state.ts): best times, the ranking tables of every mode and
the option settings, and the menu's row count at state+0x4B538 (2 or 3 rows): state+0x4AD84 to
state+0x4B53F. SLUS_003.38 and the menus set them before Puzzle Mode runs; the core starts from
the same values.

  extract_boot_state.py RAM_DUMP web/src/core/boot-state.ts

RAM_DUMP is a main-RAM dump taken at tick 1 (scripts/run-movie.sh with TP_RAM_AT=1). Tick 1's
logic (phase0_setup) writes only the screen words (state+0x4B508-0x4B527, which it sets in
full anyway) and sprite objects, so the rest is still as the boot program left it.
"""
import base64
import sys

STATE = 0x8003E668
START, END = 0x4AD84, 0x4B540


def main():
    ram = open(sys.argv[1], 'rb').read()
    a = (STATE & 0x1FFFFF) + START
    chunk = ram[a:a + END - START]
    b64 = base64.b64encode(chunk).decode()
    parts = [b64[i:i + 96] for i in range(0, len(b64), 96)]
    out = [
        '// Generated by re/tools/extract_boot_state.py from an emulator RAM dump. Do not edit.',
        "// The shared state block's best times, ranking tables and settings as the boot program",
        '// leaves them when PAZLE.EXE starts (state+0x4AD84 to state+0x4B53F).',
        f'export const BOOT_STATE_OFFSET = 0x{START:x};',
        'export const BOOT_STATE_BASE64 =',
        '  ' + ' +\n  '.join(f"'{p}'" for p in parts) + ';',
    ]
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
