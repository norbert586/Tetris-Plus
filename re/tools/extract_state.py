#!/usr/bin/env python3
"""Writes the boot program's shared state block (state = 0x8003E668) from an emulator RAM dump as
the TypeScript core loads it: the non-zero runs of 32-bit words, except the GPU and decoder work
areas the core doesn't model (packet buffers, ordering tables, LZ buffer, sprite templates:
state+0x206E4 to state+0x4AD84).

  extract_state.py RAM_DUMP web/src/core/power-on.ts POWER_ON_STATE

Used for the state SW_ON.EXE finds at power-on (TP_RAM_START=1 dump of a movie starting with
"program SW_ON"; docs/re/shell.md §6).
"""
import base64
import sys

STATE = 0x8003E668
END = 0x4B544
SKIP = (0x206E4, 0x4AD84)


def main():
    ram, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    d = open(ram, 'rb').read()
    base = STATE & 0x1FFFFF
    runs = []
    for off in range(0, END, 4):
        if SKIP[0] <= off < SKIP[1] or not any(d[base + off:base + off + 4]):
            continue
        if runs and runs[-1][1] == off:
            runs[-1][1] = off + 4
        else:
            runs.append([off, off + 4])
    lines = [
        f'// Generated by re/tools/extract_state.py from an emulator RAM dump. Do not edit.',
        '// Non-zero runs of the shared state block (offset from state = 0x8003E668, bytes).',
        f'export const {name}: [number, string][] = [',
    ]
    for a, b in runs:
        lines.append(f"  [0x{a:x}, '{base64.b64encode(d[base + a:base + b]).decode()}'],")
    lines.append('];')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(runs)} runs, {sum(b - a for a, b in runs)} bytes')


if __name__ == '__main__':
    main()
