#!/usr/bin/env python3
"""Writes the parts of a program the TypeScript core reads as data (web/src/core/rom.ts for
PAZLE.EXE, web/src/core/programs/<name>/rom.ts for the others).

  extract_core_rom.py PAZLE.EXE web/src/core/rom.ts
  extract_core_rom.py RANKING.EXE web/src/core/programs/ranking/rom.ts 0x80094000-0x80094AD0 0x800ABC90-0x800B2800

The core keeps the original's memory layout for game state (web/src/core/mem.ts), so its tables
are loaded at their original addresses: the read-only block before the code (dispatch and small
constant tables, 0x80094000-0x800955D3) and the initialised data after it (0x800D4FB0-
0x800ED7FF: shapes, levels, stages, professor scripts, sprite animations, text, sound tables).
Code is not included. Each range is stored base64-encoded with its address.
"""
import base64
import struct
import sys

RANGES = [
    ('rodata', 0x80094000, 0x800955D4),
    ('data', 0x800D4FB0, 0x800ED800),
]


def main():
    exe, out = sys.argv[1], sys.argv[2]
    ranges = RANGES
    if len(sys.argv) > 3:
        # START-END pairs: the read-only block before the code, the data after the library.
        ranges = []
        for k, r in enumerate(sys.argv[3:]):
            a, b = (int(x, 16) for x in r.split('-'))
            ranges.append(('rodata' if k == 0 else 'data', a, b))
    data = open(exe, 'rb').read()
    t_addr, t_size = struct.unpack_from('<II', data, 0x18)
    body = data[0x800:0x800 + t_size]
    lines = [
        f'// Generated by re/tools/extract_core_rom.py from {exe.split("/")[-1]} (SLUS-00338). Do not edit.',
        '// Data ranges of the original program, loaded at their original addresses (see mem.ts).',
        'export const ROM: { name: string; address: number; base64: string }[] = [',
    ]
    for name, start, end in ranges:
        chunk = body[start - t_addr:end - t_addr]
        assert len(chunk) == end - start
        lines.append(f"  {{ name: '{name}', address: 0x{start:08x}, base64:")
        b64 = base64.b64encode(chunk).decode()
        parts = [b64[i:i + 96] for i in range(0, len(b64), 96)]
        lines.append('    ' + ' +\n    '.join(f"'{p}'" for p in parts) + ' },')
    lines.append('];')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
