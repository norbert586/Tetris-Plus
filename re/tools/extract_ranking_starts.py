#!/usr/bin/env python3
"""Writes the shared state block as RANKING.EXE finds it at its main, for each run of it the
tests replay (web/test/fixtures/ranking-starts.ts): the RANKING tests start at the program's
first tick until every program before it is ported (docs/re/ranking.md §5).

  extract_ranking_starts.py OUT.ts NAME=RAM_DUMP [NAME=RAM_DUMP ...]

Each RAM_DUMP is main RAM at RANKING's main (scripts/run-movie.sh with TP_MAIN_RAM=1:
ram_main_RANKING_<counter>.bin); NAME is the movie and run (e.g. attract-cycle#1). The ranges
are those web/src/flow/power-state.ts keeps (re/tools/extract_power_state.py): the flow words,
the boot program's globals, the CD's table of contents, records and settings and the screen
words. RANKING reads nothing else that an earlier program leaves.
"""
import base64
import sys

STATE = 0x8003E668
RANGES = [(0x0, 0xC0), (0x1FCF4, 0x1FDF4), (0x20550, 0x20650), (0x4AD84, 0x4B540)]


def main():
    out = [
        '// Generated by re/tools/extract_ranking_starts.py from emulator RAM dumps. Do not edit.',
        "// The shared state block's ranges at RANKING.EXE's main, per run: offset from state",
        '// (0x8003E668) and bytes.',
        'export const RANKING_STARTS: Record<string, { offset: number; base64: string }[]> = {',
    ]
    for arg in sys.argv[2:]:
        name, path = arg.split('=', 1)
        ram = open(path, 'rb').read()
        out.append(f"  '{name}': [")
        for start, end in RANGES:
            a = (STATE & 0x1FFFFF) + start
            b64 = base64.b64encode(ram[a:a + end - start]).decode()
            parts = [b64[i:i + 96] for i in range(0, len(b64), 96)]
            out.append(f'    {{ offset: 0x{start:x}, base64:')
            out.append('      ' + ' +\n      '.join(f"'{p}'" for p in parts) + ' },')
        out.append('  ],')
    out.append('};')
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
