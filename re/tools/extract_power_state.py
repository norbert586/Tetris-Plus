#!/usr/bin/env python3
"""Writes the boot program's shared state block as the first mode program finds it at power-on
(web/src/flow/power-state.ts): what SLUS_003.38 sets before it runs SW_ON.EXE (default
settings, best times and rankings, the CD's table of contents, the screen words). The port's
whole-game runtime (web/src/flow/console.ts) starts from it, as the Puzzle-only core starts
from boot-state.ts.

  extract_power_state.py RAM_DUMP web/src/flow/power-state.ts

RAM_DUMP is main RAM at SW_ON's main (scripts/run-movie.sh with a "boot power" movie and
TP_MAIN_RAM=1: ram_main_SW_ON_00000.bin). Only the ranges below hold values anything reads;
the rest of the block is ordering tables, packet buffers and sprite templates the programs
rebuild.
"""
import base64
import sys

STATE = 0x8003E668
RANGES = [(0x0, 0xC0), (0x1FCF4, 0x1FDF4), (0x20550, 0x20650), (0x4AD84, 0x4B540)]


def main():
    ram = open(sys.argv[1], 'rb').read()
    out = [
        '// Generated by re/tools/extract_power_state.py from an emulator RAM dump. Do not edit.',
        "// The shared state block's ranges as the boot program leaves them before SW_ON.EXE: offset",
        '// from state (0x8003E668) and bytes.',
        'export const POWER_STATE: { offset: number; base64: string }[] = [',
    ]
    for start, end in RANGES:
        a = (STATE & 0x1FFFFF) + start
        b64 = base64.b64encode(ram[a:a + end - start]).decode()
        parts = [b64[i:i + 96] for i in range(0, len(b64), 96)]
        out.append(f'  {{ offset: 0x{start:x}, base64:')
        out.append('    ' + ' +\n    '.join(f"'{p}'" for p in parts) + ' },')
    out.append('];')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
